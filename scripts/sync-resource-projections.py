#!/usr/bin/env python3
"""Reproduce browser and hosted public-catalog modules; default is read-only."""
import argparse
import json
import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "company/role-library/resource-catalog.json"

def projections():
    raw = SOURCE.read_bytes()
    checked = subprocess.run(["node", str(ROOT / "scripts/resource-router.mjs"), "--check"], check=True, capture_output=True, text=True)
    receipt = json.loads(checked.stdout)
    if SOURCE.read_bytes() != raw:
        raise ValueError("Catalog changed during validation; rerun the projection build")
    data = json.loads(raw)
    if data.get("schemaVersion") != 1 or not isinstance(data.get("resources"), list):
        raise ValueError("Invalid public resource catalog")
    if len(raw) > 1024 * 1024 or len(data["resources"]) > 800:
        raise ValueError("Public resource catalog exceeds package bounds")
    # Native's canonical hash includes review/routing metadata and ignores JSON
    # formatting. Use that same identity in every generated execution plane.
    digest = receipt.get("catalogSha256")
    if receipt.get("valid") is not True or not isinstance(digest, str) or not re.fullmatch(r"[0-9a-f]{64}", digest):
        raise ValueError("Strict catalog validator did not return a valid digest")
    body = ("// Generated by scripts/sync-resource-projections.py; edit the canonical public catalog.\n"
            f'export const RESOURCE_CATALOG_SHA256 = "{digest}";\n'
            "export const RESOURCE_CATALOG = " + json.dumps(data, ensure_ascii=False, separators=(",", ":")) + ";\n")
    outputs = {
        ROOT / "desktop-shell/src/renderer/resource-library/catalog.ts": body,
        ROOT / "cloud-workspace/lib/resource-catalog.ts": body,
    }
    routing = ROOT / "desktop-shell/src/main/resourceRouting.ts"
    if routing.exists():
        outputs[ROOT / "cloud-workspace/lib/resource-routing.ts"] = routing.read_text()
    return outputs

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true")
    args = parser.parse_args()
    stale = []
    for target, body in projections().items():
        if args.write:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(body, encoding="utf-8")
        elif not target.exists() or target.read_text() != body:
            stale.append(str(target.relative_to(ROOT)))
    if stale:
        raise SystemExit("Stale resource projections: " + ", ".join(stale))
    print("Resource projections " + ("written" if args.write else "match canonical source"))

if __name__ == "__main__":
    main()
