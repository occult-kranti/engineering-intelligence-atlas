#!/usr/bin/env node
/**
 * Generate src/data/corpusCounts.ts — a tiny module carrying count-only corpus
 * constants so always-loaded chrome (Chrome.tsx, Overview.tsx) does not pull
 * the full ROLES / RESOURCES / JOBS / SKILL_PACKAGES arrays into the initial
 * bundle. Counts are derived from the source arrays, and
 * src/data/corpusCounts.test.ts asserts the constants never drift.
 *
 * Usage: node --experimental-strip-types scripts/generate-corpus-counts.mjs
 *        (or: npx tsx scripts/generate-corpus-counts.mjs)
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const { ROLES } = await import(join(root, 'src/data/roles.ts'));
const { RESOURCES } = await import(join(root, 'src/data/resources.ts'));
const { JOBS } = await import(join(root, 'src/data/jobs.ts'));
const { SKILL_PACKAGES } = await import(join(root, 'src/data/skills.ts'));

const out = `/* Generated by scripts/generate-corpus-counts.mjs from the source data
 * arrays. Count-only constants for the always-loaded chrome so the full
 * ROLES / RESOURCES / JOBS / SKILL_PACKAGES arrays stay out of the initial
 * bundle. Keep in sync: corpusCounts.test.ts verifies these against the
 * source arrays. */
export const CORPUS_COUNTS = {
  roles: ${ROLES.length},
  resources: ${RESOURCES.length},
  skillPackages: ${SKILL_PACKAGES.length},
  jobRecords: ${JOBS.recordCount},
} as const;
`;
writeFileSync(join(root, 'src/data/corpusCounts.ts'), out);
console.log('wrote src/data/corpusCounts.ts', {
  roles: ROLES.length,
  resources: RESOURCES.length,
  skillPackages: SKILL_PACKAGES.length,
  jobRecords: JOBS.recordCount,
});
