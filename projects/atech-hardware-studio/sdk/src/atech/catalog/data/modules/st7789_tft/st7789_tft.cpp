void ST7789_TFT::_drawSplash() {
    int16_t x = _tft->width() / 2 - 1 - ATECH_LOGO_EDGE_X;  // edge's right side on the centre line
    int16_t y = (_tft->height() - ATECH_LOGO_HEIGHT) / 2;
    if (_canvas) {
        // Compose in the canvas and push it as one frame (~31 ms). Drawing the
        // bitmap straight to the panel is thousands of single-pixel writes.
        // The canvas is cleared again afterwards so the app starts on black.
        _canvas->fillScreen(ST77XX_BLACK);
        _canvas->drawBitmap(x, y, ATECH_LOGO, ATECH_LOGO_WIDTH, ATECH_LOGO_HEIGHT, ST77XX_WHITE);
        _pushCanvas();
        _canvas->fillScreen(ST77XX_BLACK);
    } else {
        _tft->fillScreen(ST77XX_BLACK);
        _tft->drawBitmap(x, y, ATECH_LOGO, ATECH_LOGO_WIDTH, ATECH_LOGO_HEIGHT, ST77XX_WHITE);
    }
    _splashShowing = true;
}

void ST7789_TFT::begin() {
    // Prefer hardware SPI: a full-frame push is ~31 ms at 40 MHz, several times
    // slower in software SPI.
    //
    // Hardware host if one is free after the hosts reserved for the microSD
    // card and camera; software SPI otherwise (see atech_spi_hosts.h).
    SPIClass* spi = atech::claimDisplaySpiHost(_sclkPin, _mosiPin, _csPin);

    if (spi != nullptr) {
        _tft = new Adafruit_ST7789(spi, _csPin, _dcPin, -1);
    } else {
        _tft = new Adafruit_ST7789(_csPin, _dcPin, _mosiPin, _sclkPin, -1);
        _softSpi = true;
        Serial.println("ST7789: no hardware SPI host left, running software SPI");
    }

    _initDisplay();

    // 320x240x2 = 150 KB. Fits in internal RAM on a freshly booted S3, but not
    // always once an app has allocated its own buffers — so fall back rather than crash.
    _canvas = new GFXcanvas16(_tft->width(), _tft->height());
    if (_canvas->getBuffer() == nullptr) {
        delete _canvas;
        _canvas = nullptr;
        _directMode = true;
        Serial.println("ST7789: no RAM for the 150KB canvas, running in direct mode");
    } else {
        _canvas->fillScreen(ST77XX_BLACK);
    }

    // The logo stays on the panel until the app's first display() (or its
    // first direct-mode draw) paints over it. No blocking delay.
    _drawSplash();

    Serial.printf("ST7789 display initialized (320x240, %s)\n",
                  _canvas ? "double-buffered" : "direct");
}

void ST7789_TFT::setDirectMode(bool direct) {
    // Without a canvas there is nothing to draw into but the panel.
    _directMode = direct || _canvas == nullptr;
}

