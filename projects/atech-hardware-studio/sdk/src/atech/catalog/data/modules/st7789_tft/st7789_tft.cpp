// Midpoint ellipse — Adafruit_GFX does not provide one, so we walk the curve in
// two regions (slope < -1 then slope >= -1) and reflect into all four quadrants.
void ST7789_TFT::drawEllipse(int16_t cx, int16_t cy, int16_t rx, int16_t ry, uint16_t color) {
    if (rx <= 0 || ry <= 0) return;
    Adafruit_GFX* g = _gfx();
    int32_t rx2 = (int32_t)rx * rx;
    int32_t ry2 = (int32_t)ry * ry;
    int32_t tworx2 = 2 * rx2;
    int32_t twory2 = 2 * ry2;
    int32_t x = 0;
    int32_t y = ry;
    int32_t px = 0;
    int32_t py = tworx2 * y;
    int32_t p = ry2 - rx2 * ry + (rx2 + 2) / 4;
    while (px < py) {
        g->drawPixel(cx + x, cy + y, color);
        g->drawPixel(cx - x, cy + y, color);
        g->drawPixel(cx + x, cy - y, color);
        g->drawPixel(cx - x, cy - y, color);
        x++;
        px += twory2;
        if (p < 0) {
            p += ry2 + px;
        } else {
            y--;
            py -= tworx2;
            p += ry2 + px - py;
        }
    }
    p = ry2 * (2 * x * x + 2 * x + 1) / 2 + rx2 * (y - 1) * (y - 1) - rx2 * ry2;
    while (y >= 0) {
        g->drawPixel(cx + x, cy + y, color);
        g->drawPixel(cx - x, cy + y, color);
        g->drawPixel(cx + x, cy - y, color);
        g->drawPixel(cx - x, cy - y, color);
        y--;
        py -= tworx2;
        if (p > 0) {
            p += rx2 - py;
        } else {
            x++;
            px += twory2;
            p += rx2 - py + px;
        }
    }
}

void ST7789_TFT::fillEllipse(int16_t cx, int16_t cy, int16_t rx, int16_t ry, uint16_t color) {
    if (rx <= 0 || ry <= 0) return;
    Adafruit_GFX* g = _gfx();
    int32_t rx2 = (int32_t)rx * rx;
    int32_t ry2 = (int32_t)ry * ry;
    int32_t tworx2 = 2 * rx2;
    int32_t twory2 = 2 * ry2;
    int32_t x = 0;
    int32_t y = ry;
    int32_t px = 0;
    int32_t py = tworx2 * y;
    int32_t p = ry2 - rx2 * ry + (rx2 + 2) / 4;
    int16_t lastY = y + 1;  // sentinel — never matches a real y
    while (px < py) {
        if ((int16_t)y != lastY) {
            int16_t w = (int16_t)(2 * x + 1);
            g->drawFastHLine(cx - x, cy + y, w, color);
            if (y != 0) g->drawFastHLine(cx - x, cy - y, w, color);
            lastY = y;
        }
        x++;
        px += twory2;
        if (p < 0) {
            p += ry2 + px;
        } else {
            y--;
            py -= tworx2;
            p += ry2 + px - py;
        }
    }
    p = ry2 * (2 * x * x + 2 * x + 1) / 2 + rx2 * (y - 1) * (y - 1) - rx2 * ry2;
    while (y >= 0) {
        int16_t w = (int16_t)(2 * x + 1);
        g->drawFastHLine(cx - x, cy + y, w, color);
        if (y != 0) g->drawFastHLine(cx - x, cy - y, w, color);
        y--;
        py -= tworx2;
        if (p > 0) {
            p += rx2 - py;
        } else {
            x++;
            px += twory2;
            p += rx2 - py + px;
        }
    }
}

