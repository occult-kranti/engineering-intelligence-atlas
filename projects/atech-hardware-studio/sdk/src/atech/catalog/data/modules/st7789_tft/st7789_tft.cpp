/**
 * @file st7789_tft.cpp
 * @brief ST7789 320x240 TFT Color Display implementation for Atech
 *
 * Uses an off-screen GFXcanvas16 framebuffer (150KB RAM) for flicker-free drawing.
 * All draw calls write to the canvas; display() pushes the whole frame at once.
 */

#include "st7789_tft.h"
#include "atech_spi_hosts.h"
#include "atech_soft_spi.h"

// Native panel size, portrait. Landscape swaps them.
static const int16_t PANEL_W = 240;
static const int16_t PANEL_H = 320;

ST7789_TFT::ST7789_TFT(int sclkPin, int csPin, int mosiPin, int dcPin)
    : _sclkPin(sclkPin)
    , _csPin(csPin)
    , _mosiPin(mosiPin)
    , _dcPin(dcPin)
    , _tft(nullptr)
    , _canvas(nullptr)
    , _directMode(false)
    , _splashShowing(false)
    , _softSpi(false)
{
}

void ST7789_TFT::_applyMadctl(uint8_t r) {
    // Adafruit_ST7789::setRotation always writes RGB order; add BGR (0x08) when the panel wants it.
    // MADCTL base values per rotation: 0=MX|MY(0xC0), 1=MY|MV(0xA0), 2=none(0x00), 3=MX|MV(0x60)
    static const uint8_t madctl_base[] = {0xC0, 0xA0, 0x00, 0x60};
    uint8_t madctl = madctl_base[r & 0x03] | (ST7789_TFT_BGR ? 0x08 : 0x00);
    _tft->sendCommand(ST77XX_MADCTL, &madctl, 1);
}

// The panel powers up from the same 3V3 rail as the ESP32, and its RST is only
// a pull-up, so nothing holds it in reset while the supply settles. Straight
// after a cold plug-in, begin() runs ~140 ms after power-on. On the V1.1 module
// (2026-09-23) the stock init left the panel dark after a re-plug, while a
// flash, which leaves the panel powered, never did. Waiting out the power-up
// and repeating the wake with the datasheet's 120 ms lit it on every re-plug.
// The small screen does not need this: Adafruit's ST7735 init already waits
// 500 ms after sleep-out.
static const unsigned long PANEL_POWER_UP_MS = 300;

void ST7789_TFT::_initDisplay() {
    // millis() counts from the ESP32's own reset, so this also waits (~160 ms)
    // after a flash or reset, when the panel never lost power. Cheap, and the
    // ESP32 cannot tell the two apart: its reset cause reads UNKNOWN on USB power-up.
    while (millis() < PANEL_POWER_UP_MS) delay(5);

    // init() starts with a software reset, which is all this module has: RST is tied high.
    _tft->init(PANEL_W, PANEL_H);
    delay(150);  // Let controller finish init (datasheet: 120ms min after sleep out)
    // Landscape, 320x240. 3 is upright on the board's right-hand column, like
    // ST7735_TFT; codegen adds setRotation(1) for a left-hand pair, which is the
    // orientation verified on hardware (ports 1+2, 2026-09-22).
    _tft->setRotation(3);
    _applyMadctl(3);
    _tft->invertDisplay(ST7789_TFT_INVERT);
    _tft->setSPISpeed(40000000);
    _tft->fillScreen(ST77XX_BLACK);

    // Wake again with the full sleep-out time. Adafruit's ST7789 init only waits
    // 10 ms after SLPOUT, which a cold panel does not always take.
    _tft->sendCommand(ST77XX_SLPOUT);
    delay(120);
    _tft->sendCommand(ST77XX_DISPON);
    delay(20);
}

