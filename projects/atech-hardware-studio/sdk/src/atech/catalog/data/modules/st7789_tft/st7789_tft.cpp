void ST7789_TFT::setRotation(uint8_t r) {
    if (!_tft) return;
    _tft->setRotation(r);
    _applyMadctl(r);

    // The canvas is pushed as one raw block, so its buffer must have the panel's
    // shape. Going landscape <-> portrait means a new canvas of the same size.
    if (_canvas && _canvas->width() != _tft->width()) {
        delete _canvas;
        _canvas = new GFXcanvas16(_tft->width(), _tft->height());
        if (_canvas->getBuffer() == nullptr) {
            delete _canvas;
            _canvas = nullptr;
            _directMode = true;
            Serial.println("ST7789: canvas lost on rotation, running in direct mode");
        } else {
            _canvas->fillScreen(ST77XX_BLACK);
        }
    }

    // Pixels already on the panel do not move when the scan direction changes,
    // so a splash drawn at begin()'s rotation would sit upside down on a
    // left-side pair once codegen flips it. Redraw it the right way up.
    if (_splashShowing) _drawSplash();
}

