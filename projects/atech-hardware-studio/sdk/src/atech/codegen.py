# Host -> board actions. One JSON line per action:
#   {"action":"<key>","value":"<string>"}
# The firmware answers every action with one line:
#   {"type":"ack","payload":{"action":"<key>","ok":true}}
#   {"type":"ack","payload":{"action":"<key>","ok":false,"error":"unknown action"}}
_ACTIONS_RUNTIME = """\
// ---- atech actions (host -> board) ----
// `atech send <key> [value]` / board.call(key, value). Module actions are dispatched
// below. For your own action, test `atech_action` in code.loop and call atechDone():
//   if (atech_action == "buzz") { spk.playTone(880, 100); atechDone(); }
String atech_action;   // key of the action waiting for user code ("" = none)
String atech_value;    // its value
static String _atech_line;
static const char* _atech_error = nullptr;

// Call from a handler (or code.loop) when the action could not be carried out:
// the host then gets ok:false with this message instead of a false success.
static void atechFail(const char* why) { _atech_error = why; }

static String atechJsonString(const String& json, const char* field, int from = 0, int* endOut = nullptr) {
    String pat = String("\\"") + field + "\\":";
    int i = json.indexOf(pat, from);
    if (i < 0) return String();
    i += pat.length();
    while (i < (int)json.length() && json[i] == ' ') i++;
    if (i >= (int)json.length() || json[i] != '"') return String();
    String out;
    for (i++; i < (int)json.length(); i++) {
        char c = json[i];
        if (c == '\\\\' && i + 1 < (int)json.length()) {
            char n = json[++i];
            out += (n == 'n') ? '\\n' : (n == 't') ? '\\t' : n;
        } else if (c == '"') {
            break;
        } else {
            out += c;
        }
    }
    if (endOut) *endOut = i;
    return out;
}

// Number stored under "field" in a flat JSON object, e.g. atechNum(value, "r", 0).
static long atechNum(const String& json, const char* field, long fallback) {
    String pat = String("\\"") + field + "\\":";
    int i = json.indexOf(pat);
    if (i < 0) return fallback;
    i += pat.length();
    while (i < (int)json.length() && (json[i] == ' ' || json[i] == '"')) i++;
    if (i >= (int)json.length() || !(isDigit(json[i]) || json[i] == '-')) return fallback;
    return json.substring(i).toInt();
}

// Number array stored under "field", e.g. {"positions":[1,2,3]}. Returns how many were read.
static int atechNums(const String& json, const char* field, long* out, int maxN) {
    String pat = String("\\"") + field + "\\":";
    int i = json.indexOf(pat);
    if (i < 0) return 0;
    i = json.indexOf('[', i);
    if (i < 0) return 0;
    int n = 0;
    i++;
    while (i < (int)json.length() && n < maxN) {
        while (i < (int)json.length() && (json[i] == ' ' || json[i] == ',')) i++;
        if (i >= (int)json.length() || json[i] == ']') break;
        out[n++] = json.substring(i).toInt();
        while (i < (int)json.length() && json[i] != ',' && json[i] != ']') i++;
    }
    return n;
}

static bool atechTruthy(const String& v) {
    return v == "true" || v == "1" || v == "on";
}

static void atechAck(const String& key, bool ok, const char* error = nullptr) {
    Serial.print("{\\"type\\":\\"ack\\",\\"payload\\":{\\"action\\":\\"");
    Serial.print(key);
    Serial.print(ok ? "\\",\\"ok\\":true" : "\\",\\"ok\\":false");
    if (error) { Serial.print(",\\"error\\":\\""); Serial.print(error); Serial.print("\\""); }
    Serial.println("}}");
}

// Call from code.loop after handling `atech_action` yourself.
static void atechDone() {
    if (!atech_action.length()) return;
    atechAck(atech_action, _atech_error == nullptr, _atech_error);
    _atech_error = nullptr;
    atech_action = "";
    atech_value = "";
}

static bool atechDispatch(const String& key, const String& value) {
{{ dispatch }}
    return false;
}

static void atechPollAction() {
    while (Serial.available()) {
        char c = (char)Serial.read();
        if (c == '\\r') continue;
        if (c != '\\n') {
            if (_atech_line.length() < 4096) _atech_line += c;
            continue;
        }
        String line = _atech_line;
        _atech_line = "";
        int end = 0;
        String key = atechJsonString(line, "action", 0, &end);
        if (!key.length()) continue;           // not an action line
        String value = atechJsonString(line, "value", end);
        _atech_error = nullptr;
        if (atechDispatch(key, value)) {
            atechAck(key, _atech_error == nullptr, _atech_error);
            _atech_error = nullptr;
        } else {
            atech_action = key;                 // offered to code.loop for this pass
            atech_value = value;
        }
        return;                                 // one action per loop pass
    }
}

static void atechFinishAction() {
    if (atech_action.length()) {
        atechAck(atech_action, false, "unknown action");
        atech_action = "";
        atech_value = "";
    }
}
"""



_PLATFORMIO_INI = """\
; Generated by atech-sdk. Re-run `atech build` to refresh.
[env:{{ env }}]
platform = espressif32
board = {{ env }}
framework = {{ framework }}
monitor_speed = 115200
; Explicit reset flags make flashing reliable over the ESP32-S3 native
; USB-CDC, which otherwise often hangs at "Connecting...". The rate is
; per-board: some USB-JTAG bridges fail esptool's baud change above 115200.
upload_speed = {{ upload_speed }}
upload_flags =
    --before=default_reset
    --after=hard_reset
; ARDUINO_USB_MODE=1 + CDC_ON_BOOT=1 route `Serial` to the native USB-CDC class on
; ESP32-S3, which is what the host-side `atech.runtime.Board` listens to. It also
; gives Serial a setTxTimeoutMs(...) method so firmware can run untethered without
; blocking when no host is reading.
build_flags =
    -DCORE_DEBUG_LEVEL=0
    -DARDUINO_USB_MODE=1
    -DARDUINO_USB_CDC_ON_BOOT=1
{%- if lib_deps %}
lib_deps =
{%- for dep in lib_deps %}
    {{ dep }}
{%- endfor %}
{%- endif %}
"""


def _render(template_text: str, context: dict) -> str:
    return _JINJA.from_string(template_text).render(**context)


def _port_gpios(board: BoardSpec, port_id: str) -> tuple[int, int]:
    """(Line A, Line B) GPIOs for a port; 0 for an absent line."""
    p = board.port(port_id)
    a = p.pins[0].gpio if p.pins else 0
    b = p.pins[1].gpio if len(p.pins) > 1 else 0
    return a, b


def _module_context(
    project_module: "ProjectModule",
    board: BoardSpec,
    spec: ModuleSpec,
) -> dict:
    """Variables every module template can reference.

    Single-width modules use the one port's Line A/B as pin_a/pin_b.

    Double-width modules span two adjacent ports. Pin assignment mirrors the
    firmware/backend ``resolve_double_module_pins`` rule (the single source of
    truth): the *lower-numbered* port is primary, and **on the left side of the
    board the two port groups are swapped** — pin_a/pin_b come from the
    secondary (higher) port and pin_a2/pin_b2 from the primary — because a module
    snaps into the left column rotated 180° vs the right. This makes orientation
    automatic from the board geometry, so the order the user writes the ports in
    doesn't matter.
    """
    ctx: dict = {
        "instance": project_module.instance,
        "module_id": project_module.module_id,
        "class_name": spec.driver.class_name,
    }

    ports = list(project_module.ports)
    if len(ports) == 1:
        pin_a, pin_b = _port_gpios(board, ports[0])
        if getattr(project_module, "swap_lines", False):
            pin_a, pin_b = pin_b, pin_a
        ctx.update(port_id=ports[0], pin_a=pin_a, pin_b=pin_b)
        return ctx

    # Double-width: primary = lower-numbered port; secondary = higher.
    lower, higher = sorted(ports, key=lambda pid: board.port(pid).slot_number or 0)
    primary_side = (board.port(lower).side or "right").lower()
    lo_a, lo_b = _port_gpios(board, lower)
    hi_a, hi_b = _port_gpios(board, higher)

    if primary_side == "left":
        # Left column is mirrored: secondary (higher) port supplies pin_a/pin_b.
        (pa, pb, pid1), (pa2, pb2, pid2) = (hi_a, hi_b, higher), (lo_a, lo_b, lower)
    else:
        (pa, pb, pid1), (pa2, pb2, pid2) = (lo_a, lo_b, lower), (hi_a, hi_b, higher)

    ctx.update(
        port_id=pid1, pin_a=pa, pin_b=pb,
        port_id_2=pid2, pin_a2=pa2, pin_b2=pb2,
    )
    return ctx


# --------------------------------------------------------- boot diagnostics

_RESET_REASON_SWITCH = """\
esp_reset_reason_t _rr = esp_reset_reason();
const char* _rrs;
switch (_rr) {
    case ESP_RST_POWERON:   _rrs = "POWERON";   break;
    case ESP_RST_EXT:       _rrs = "EXT";       break;
    case ESP_RST_SW:        _rrs = "SOFTWARE";  break;
    case ESP_RST_PANIC:     _rrs = "PANIC";     break;
    case ESP_RST_INT_WDT:   _rrs = "INT_WDT";   break;
    case ESP_RST_TASK_WDT:  _rrs = "TASK_WDT";  break;
    case ESP_RST_WDT:       _rrs = "WDT";       break;
    case ESP_RST_BROWNOUT:  _rrs = "BROWNOUT";  break;
    case ESP_RST_DEEPSLEEP: _rrs = "DEEPSLEEP"; break;
    default:                _rrs = "UNKNOWN";   break;
}
"""


def render_diagnostics(project: "Project", board: BoardSpec, specs: dict) -> str:
    """C++ that prints a one-line JSON boot report: reset reason, heap, modules.

    Wire shape (read by ``atech check`` / ``Board.diagnostics()``):
      {"type":"boot","payload":{"reset_reason":"POWERON","free_heap":N,
        "modules":[{"instance":"th","module":"aht20","ok":true,"detectable":true}]}}
    """
    lines: list[str] = ["{"]
    lines.append(_RESET_REASON_SWITCH.rstrip())
    lines.append('Serial.print("{\\"type\\":\\"boot\\",\\"payload\\":{\\"reset_reason\\":\\"");')
    lines.append("Serial.print(_rrs);")
    lines.append('Serial.print("\\",\\"free_heap\\":");')
    lines.append("Serial.print((unsigned)ESP.getFreeHeap());")
    lines.append('Serial.print(",\\"modules\\":[");')

    for idx, pm in enumerate(project.modules):
        spec = specs[pm.module_id]
        ctx = _module_context(pm, board, spec)
        sep = "" if idx == 0 else ","
        prefix = (
            f'{{\\"instance\\":\\"{pm.instance}\\",'
            f'\\"module\\":\\"{pm.module_id}\\",\\"ok\\":'
        )
        lines.append(f'Serial.print("{sep}{prefix}");')
        if spec.health_check:
            expr = _render(spec.health_check, ctx).strip()
            lines.append(f'Serial.print(({expr}) ? "true" : "false");')
            lines.append('Serial.print(",\\"detectable\\":true}");')
        else:
            # No read-back: report initialized, but presence can't be verified.
            lines.append('Serial.print("true");')
            lines.append('Serial.print(",\\"detectable\\":false}");')

    lines.append('Serial.println("]}}");')
    lines.append("}")
    return "\n".join(lines)


# ----------------------------------------------------------------- actions


def render_actions(project: "Project", board: BoardSpec, specs: dict) -> str:
    """C++ for the host->board action layer: line reader, dispatch, acknowledgements.

    Every action a placed module declares *with a handler* becomes one branch of
    ``atechDispatch``. Actions without a handler are not dispatched; the firmware
    answers them (and any other unknown key) with ``ok:false``.
    """
    branches: list[str] = []
    for pm in project.modules:
        spec = specs[pm.module_id]
        ctx = _module_context(pm, board, spec)
        for action in spec.actions:
            if not action.handler:
                continue
            key = _render(action.key, ctx).strip()
            body = _render(action.handler, ctx).strip()
            branches.append(
                f'    if (key == "{key}") {{\n'
                + "\n".join(f"        {line}" for line in body.splitlines())
                + "\n        return true;\n    }"
            )
    dispatch = "\n".join(branches) if branches else "    (void)key; (void)value;"
    return _ACTIONS_RUNTIME.replace("{{ dispatch }}", dispatch).rstrip()


# --------------------------------------------------------------- file emit


def render_main_cpp(project: "Project") -> str:
    board = project.board_spec
    specs = project.module_specs()

    includes: list[str] = []
    globals_blocks: list[str] = []
    setup_blocks: list[str] = []
    loop_blocks: list[str] = []

    seen_includes: set[str] = set()
    for pm in project.modules:
        spec = specs[pm.module_id]
        ctx = _module_context(pm, board, spec)

        for header in [*spec.driver.shared, spec.driver.header]:
            if header not in seen_includes:
                includes.append(header)
                seen_includes.add(header)

        if spec.templates.globals:
            globals_blocks.append(_render(spec.templates.globals, ctx).rstrip())
        if spec.templates.setup:
            setup_blocks.append(_render(spec.templates.setup, ctx).strip())
        if spec.templates.loop:
            loop_blocks.append(_render(spec.templates.loop, ctx).strip())

    # A microSD card needs a hardware SPI host; a screen can bit-bang. Promise the card
    # its host before any module's begin(), so a screen set up first does not take it.
    spi_hosts = sum(1 for pm in project.modules if specs[pm.module_id].spi_host)
    if spi_hosts:
        setup_blocks.insert(0, f"atech::reserveSpiHosts({spi_hosts});   // hardware SPI for the microSD card, before any screen starts")

    main_ctx = {
        "project": project,
        "board": board,
        "includes": includes,
        "globals_blocks": globals_blocks,
        "setup_blocks": setup_blocks,
        "loop_blocks": loop_blocks,
        "user_globals": (getattr(project, "globals_code", "") or "").strip(),
        "user_setup": (project.setup_code or "").strip(),
        "user_loop": (project.loop_code or "").strip(),
        "diagnostics_block": render_diagnostics(project, board, specs),
        "actions_block": render_actions(project, board, specs),
        "host_actions": getattr(project, "host_actions", True),
        "feedback_block": render_feedback(project),
    }
    return _render(_MAIN_CPP_TEMPLATE, main_ctx)


def render_platformio_ini(project: "Project") -> str:
    board = project.board_spec
    deps: list[str] = []
    seen: set[str] = set()
    module_deps = [dep for spec in project.module_specs().values() for dep in spec.lib_deps]
    for dep in module_deps + list(getattr(project, "libraries", [])):
        if dep not in seen:
            deps.append(dep)
            seen.add(dep)
    ctx = {
        "env": board.platformio_env,
        "framework": board.platformio_framework,
        "upload_speed": board.upload_speed,
        "lib_deps": deps,
    }
    return _render(_PLATFORMIO_INI, ctx)


def render_project_readme(project: "Project") -> str:
    board = project.board_spec
    specs = project.module_specs()
    lines: list[str] = []
    lines.append(f"# {project.name}")
    lines.append("")
    lines.append(f"Generated firmware for **{board.name}** (`{board.id}`).")
    lines.append("")
    lines.append("## Modules")
    lines.append("")
    for pm in project.modules:
        spec = specs[pm.module_id]
        ports = ", ".join(pm.ports)
        lines.append(f"- **{spec.name}** (`{pm.module_id}`) as `{pm.instance}` on `{ports}`")
    lines.append("")
    lines.append("## Build & flash")
    lines.append("")
    lines.append("This folder is generated. Change `project.yaml` one level up and run, from there:")
    lines.append("")
    lines.append("```bash")
    lines.append("atech build .")
    lines.append("atech upload .")
    lines.append("```")
    lines.append("")
    lines.append("It is also a plain PlatformIO project (`pio run`, `pio run -t upload`), but")
    lines.append("anything edited here is overwritten by the next `atech build`.")
    lines.append("")
    return "\n".join(lines)


# Files in a module folder that describe the module and are not firmware source.
_NOT_FIRMWARE = frozenset({"module.yaml", "sim.yaml"})


def generate_project(project: "Project", out_dir: Path) -> Path:
    """Write a complete PlatformIO project to ``out_dir`` and return the path."""
    project.ensure_valid()

    out_dir.mkdir(parents=True, exist_ok=True)
    src_dir = out_dir / "src"
    src_dir.mkdir(exist_ok=True)
    lib_dir = out_dir / "lib"
    lib_dir.mkdir(exist_ok=True)

    # platformio.ini
    (out_dir / "platformio.ini").write_text(render_platformio_ini(project), encoding="utf-8")

    # main.cpp
    (src_dir / "main.cpp").write_text(render_main_cpp(project), encoding="utf-8")

    # Drivers: one library per unique module (deduped by id). External
    # modules (Project.use_modules_from / modules_path) win over bundled.
    extras = list(project.extra_module_paths)
    seen: set[str] = set()
    for pm in project.modules:
        if pm.module_id in seen:
            continue
        seen.add(pm.module_id)
        module_lib = lib_dir / f"atech_{pm.module_id}"
        module_lib.mkdir(exist_ok=True)
        for filename, blob in iter_module_files(pm.module_id, extra_paths=extras):
            if filename in _NOT_FIRMWARE:
                continue
            (module_lib / filename).write_bytes(blob)

    # Studio's helpers, in every project
    helpers_lib = lib_dir / "atech_shared"
    helpers_lib.mkdir(exist_ok=True)
    for filename, blob in iter_shared_helper_files():
        (helpers_lib / filename).write_bytes(blob)

    # Shared drivers (the I2C buses): one library, whichever modules need them.
    if any(spec.driver.shared for spec in project.module_specs().values()):
        shared_lib = lib_dir / "atech_drivers"
        shared_lib.mkdir(exist_ok=True)
        for filename, blob in iter_shared_driver_files():
            (shared_lib / filename).write_bytes(blob)

    # Per-project README + the project.yaml round-trip
    (out_dir / "README.md").write_text(render_project_readme(project), encoding="utf-8")
    (out_dir / "project.yaml").write_text(project.to_yaml(), encoding="utf-8")

    return out_dir
