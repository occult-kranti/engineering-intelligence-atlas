#!/usr/bin/env node
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { STYLES, rulesFor, cssFor } from './effects.mjs';
const here=path.dirname(fileURLToPath(import.meta.url));
const publicDir=path.resolve(here,'../../site-source/public/design-backgrounds');
fs.mkdirSync(publicDir,{recursive:true});
fs.writeFileSync(path.join(here,'effects.css'),`/* Generated by build.mjs from original effects.mjs. */\n${STYLES.map(style=>rulesFor(style,`.effect-${style.id}`)).join('\n\n')}\n`);
fs.writeFileSync(path.join(here,'styles.json'),JSON.stringify(STYLES.map(({css,...style})=>({...style,approximation:true,default_motion:'off',css_bytes:Buffer.byteLength(cssFor(STYLES.find(s=>s.id===style.id)))})),null,2)+'\n');
for(const file of ['index.html','studio.css','effects.css','studio.mjs','effects.mjs','README.md','style-briefs.md','sources.json','styles.json']) fs.copyFileSync(path.join(here,file),path.join(publicDir,file));
console.log(JSON.stringify({styles:STYLES.length,public_path:'site-source/public/design-backgrounds/',external_images:0,motion_default:'off'}));
